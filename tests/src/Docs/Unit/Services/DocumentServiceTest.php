<?php

declare(strict_types=1);

use AIArmada\Docs\Contracts\DocumentPaymentRecorder;
use AIArmada\Docs\Data\DocType;
use AIArmada\Docs\Features\Numbering\Actions\SequenceManager;
use AIArmada\Docs\Models\Doc;
use AIArmada\Docs\Numbering\DocumentNumberRegistry;
use AIArmada\Docs\Features\Lifecycle\Actions\ManageDocumentRecords;
use AIArmada\Docs\Services\DocTotals;
use AIArmada\Docs\States\Draft;
use AIArmada\Docs\States\Paid;
use AIArmada\Docs\States\PartiallyPaid;
use AIArmada\Docs\States\Sent;
use Illuminate\Foundation\Testing\RefreshDatabase;

uses(RefreshDatabase::class);

beforeEach(function (): void {
    $this->sequenceManager = new SequenceManager;
    $this->numberRegistry = new DocumentNumberRegistry;
    $this->service = new ManageDocumentRecords(
        $this->numberRegistry,
        $this->sequenceManager,
        new DocTotals,
    );
});

test('can create a document from type', function (): void {
    $data = [
        'issue_date' => now(),
        'currency' => 'USD',
        'items' => [
            [
                'quantity' => 2,
                'unit_price_minor' => 100,
                'tax_amount_minor' => 10,
            ],
        ],
    ];

    $doc = $this->service->createFromType(DocType::Invoice, $data);

    expect($doc)
        ->toBeInstanceOf(Doc::class)
        ->doc_number->not->toBeNull() // Generated by real sequence
        ->doc_type->toBe(DocType::Invoice->value)
        ->subtotal_minor->toBe(200)
        ->tax_amount_minor->toBe(10)
        ->total_minor->toBe(210);

    expect($doc->status->equals(Draft::class))->toBeTrue();

    // Verify version created
    expect($doc->versions)->toHaveCount(1);
    expect($doc->versions->first()->change_summary)->toBe('Initial creation');
});

test('can update a document', function (): void {
    $doc = Doc::factory()->create([
        'doc_number' => 'INV-OLD',
        'subtotal_minor' => 100,
        'total_minor' => 110,
    ]);

    $data = [
        'notes' => 'Updated notes',
        'items' => [
            [
                'quantity' => 1,
                'unit_price_minor' => 200,
                'tax_amount_minor' => 20,
            ],
        ],
    ];

    $updatedDoc = $this->service->update($doc, $data);

    expect($updatedDoc->fresh())
        ->notes->toBe('Updated notes')
        ->subtotal_minor->toBe(200)
        ->total_minor->toBe(220);

    // Verify new version created
    expect($doc->versions)->toHaveCount(1); // Factory might not create one, service creates one
    expect($doc->versions->last()->change_summary)->toBe('Document updated');
});

test('can calculate totals', function (): void {
    $items = [
        [
            'quantity' => 2,
            'unit_price_minor' => 50,
            'tax_amount_minor' => 5,
        ],
        [
            'quantity' => 1,
            'unit_price_minor' => 100,
            'tax_amount_minor' => 10,
        ],
    ];

    $totals = $this->service->calculateTotals($items, 10); // 10 discount

    // Subtotal: (2*50) + (1*100) = 200
    // Tax: (2*5) + (1*10) = 15 (assuming tax_amount is per-line total tax)
    // Total: 200 + 15 - 10 = 205

    expect($totals['subtotal_minor'])->toBe(200)
        ->and($totals['tax_amount_minor'])->toBe(15)
        ->and($totals['total_minor'])->toBe(205);
});

test('can record payment', function (): void {
    $doc = Doc::factory()->create([
        'total_minor' => 100,
        'status' => Sent::class,
    ]);

    $paymentId = app(DocumentPaymentRecorder::class)->record((string) $doc->getKey(), [
        'amount_minor' => 50,
        'payment_method' => 'bank_transfer',
        'reference' => 'REF123',
    ]);
    $payment = $doc->payments()->findOrFail($paymentId);

    expect($payment->amount_minor)->toBe(50);
    expect($doc->fresh()->status->equals(PartiallyPaid::class))->toBeTrue();

    // Pay remaining
    app(DocumentPaymentRecorder::class)->record((string) $doc->getKey(), [
        'amount_minor' => 50,
        'payment_method' => 'bank_transfer',
    ]);

    expect($doc->fresh()->status->equals(Paid::class))->toBeTrue();
});

test('can clone a document', function (): void {
    $original = Doc::factory()->create([
        'doc_type' => DocType::Invoice,
        'currency' => 'USD',
        'items' => [['name' => 'Item 1', 'quantity' => 1, 'unit_price_minor' => 100]],
    ]);

    $clone = $this->service->clone($original);

    expect($clone->currency)->toBe('USD')
        ->and($clone->doc_number)->not->toBe($original->doc_number)
        ->and($clone->metadata['cloned_from'])->toBe($original->id);
});

test('can convert a document', function (): void {
    $source = Doc::factory()->create([
        'doc_type' => DocType::Quotation,
        'doc_number' => 'QUO-123',
        'subtotal_minor' => 100,
        'tax_amount_minor' => 10,
        'discount_amount_minor' => 0,
        'total_minor' => 110,
        'items' => [['name' => 'Item 1', 'quantity' => 1, 'unit_price_minor' => 100]],
    ]);

    $converted = $this->service->convert($source, DocType::Invoice);

    expect($converted)
        ->toBeInstanceOf(Doc::class)
        ->doc_type->toBe(DocType::Invoice->value)
        ->subtotal_minor->toBe(100)
        ->tax_amount_minor->toBe(10)
        ->total_minor->toBe(110)
        ->metadata->toHaveKey('converted_from')
        ->metadata->converted_from->doc_number->toBe('QUO-123');
});

test('preserves document financial terms after a partial payment while allowing notes', function (): void {
    $doc = Doc::factory()->create([
        'status' => Sent::class,
        'currency' => 'MYR',
        'subtotal_minor' => 100,
        'tax_amount_minor' => 0,
        'discount_amount_minor' => 0,
        'total_minor' => 100,
        'items' => [['quantity' => 1, 'unit_price_minor' => 100]],
    ]);

    app(DocumentPaymentRecorder::class)->record((string) $doc->getKey(), [
        'amount_minor' => 50,
        'payment_method' => 'bank_transfer',
    ]);

    foreach ([
        ['currency' => 'USD'],
        ['items' => [['quantity' => 1, 'unit_price_minor' => 20]]],
        ['discount_amount_minor' => 75],
    ] as $changes) {
        expect(fn () => $this->service->update($doc, $changes))
            ->toThrow(InvalidArgumentException::class, 'Document financial terms cannot change');
    }

    $updated = $this->service->update($doc, [
        'currency' => 'MYR',
        'items' => $doc->items,
        'discount_amount_minor' => 0,
        'notes' => 'Payment reference confirmed.',
    ]);

    expect($updated->currency)->toBe('MYR')
        ->and($updated->total_minor)->toBe(100)
        ->and($updated->notes)->toBe('Payment reference confirmed.')
        ->and($updated->status->equals(PartiallyPaid::class))->toBeTrue();
});

test('cloning and converting itemless documents preserve their financial snapshot', function (): void {
    $source = Doc::factory()->create([
        'doc_type' => DocType::Quotation,
        'currency' => 'MYR',
        'items' => [],
        'subtotal_minor' => 1000,
        'tax_amount_minor' => 60,
        'discount_amount_minor' => 100,
        'total_minor' => 960,
    ]);

    $source->total_minor = 1;

    foreach ([$this->service->clone($source), $this->service->convert($source, DocType::Invoice)] as $copy) {
        expect($copy->subtotal_minor)->toBe(1000)
            ->and($copy->tax_amount_minor)->toBe(60)
            ->and($copy->discount_amount_minor)->toBe(100)
            ->and($copy->total_minor)->toBe(960)
            ->and($copy->items)->toBe([])
            ->and($copy->status->equals(Draft::class))->toBeTrue();
    }
});
